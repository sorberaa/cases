let currentLanguage = "uk";

function getLanguage() {
  const saved = localStorage.getItem("printcase_lang");
  if (saved === "uk" || saved === "ru") {
    return saved;
  }
  // За замовчуванням українська
  return "uk";
}

function setLanguage(lang) {
  if (lang !== "uk" && lang !== "ru") return;
  currentLanguage = lang;
  localStorage.setItem("printcase_lang", lang);
  document.documentElement.lang = lang;

  // Оновлюємо тексти на сторінці
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.textContent = TRANSLATIONS[lang][key];
    }
  });

  // Оновлюємо плейсхолдери
  const placeholders = document.querySelectorAll("[data-i18n-ph]");
  placeholders.forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
      el.placeholder = TRANSLATIONS[lang][key];
    }
  });

  // Оновлюємо перемикачі мови в UI
  const togglers = document.querySelectorAll(".lang-btn");
  togglers.forEach((btn) => {
    if (btn.getAttribute("data-lang") === lang) {
      btn.classList.add("active");
    } else {
      btn.classList.remove("active");
    }
  });

  // Оновлюємо динамічні списки локацій
  if (window.renderLocations) {
    window.renderLocations(lang);
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getLanguage();
  setLanguage(initialLang);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      const selected = btn.getAttribute("data-lang");
      setLanguage(selected);
    });
  });
});

